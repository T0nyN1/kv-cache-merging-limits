"""Paired statistics for the second-model runs (Qwen2.5-7B-Instruct, RTX PRO 6000, bf16, eager):
runs/qwen_checks/<name>/persample_*.json against the pooled-SnapKV base in runs/qwen_checks/base_dev.
Conventions of Table 2 / experiments/h100_checks_report.py: Delta = mean paired difference x100, 20,000-resample
bootstrap over the concatenated pairs, two-sided sign test, 20,000 sign-flip permutations over samples, exact
sign flip over the eight task means; 'resolved' = CI excludes 0 and both permutation p < 0.05.
Usage: python experiments/qwen_checks_report.py [runs/qwen_checks]   -> writes <dir>/REPORT.md"""
import csv, glob, itertools, json, os, sys
from math import comb
import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
D = sys.argv[1] if len(sys.argv) > 1 else "runs/qwen_checks"
D = D if os.path.isabs(D) else os.path.join(ROOT, D)
SNAP = "_snapkv_observation_window_32_per_head_false_pool_kernel_7.json"
ROWS = [  # (label, dir, suffix, base dir, base suffix)
    ("dense (no compression) vs pooled SnapKV", "dense", "_baseline.json", "base_dev", SNAP),
    ("fixed-key construction (otkv8) vs pooled SnapKV", "otkv8", "_otkv8_observation_window_32_per_head_false_pool_kernel_7.json", "base_dev", SNAP),
    ("KeepKV, keys rewritten, vs pooled SnapKV", "keepkv", "_keepkv.json", "base_dev", SNAP),
    ("KeepKV, same merges, keys fixed, vs pooled SnapKV", "keepkv_fixed", "_keepkv_keys_fixed.json", "base_dev", SNAP),
    ("KeepKV keys fixed vs keys rewritten (direct contrast)", "keepkv_fixed", "_keepkv_keys_fixed.json", "keepkv", "_keepkv.json"),
    ("SelKV on pooled SnapKV vs pooled SnapKV", "selkv", "_selkv_selector_snapkv.json", "base_dev", SNAP),
    ("KVMerger (delta=0.75) on pooled SnapKV vs pooled SnapKV", "kvmerger", "_kvmerger_observation_window_32_per_head_false_pool_kernel_7.json", "base_dev", SNAP),
    ("VWS vs pooled SnapKV", "vws", "_otkv7_auto_regime_false.json", "base_dev", SNAP),
    ("PyramidKV vs pooled SnapKV", "pyramidkv", "_pyramidkv_observation_window_32_per_head_false.json", "base_dev", SNAP),
    ("KeepKV merge=false vs pooled SnapKV (bit-identity gate)", "keepkv_off", "_keepkv_merge_false.json", "base_dev", SNAP),
]
rng = np.random.default_rng(0)

def load(d, suf):
    out = {}
    for f in glob.glob(os.path.join(D, d, "persample_*" + suf)):
        J = json.load(open(f)); out[J["task"]] = np.array(J["scores"], float)
    return out

def paired(m, b):
    tasks = sorted(b); d = {t: (m[t] - b[t]) * 100 for t in tasks}
    tm = np.array([d[t].mean() for t in tasks]); allD = np.concatenate([d[t] for t in tasks]); delta = tm.mean()
    bs = allD[rng.integers(0, len(allD), (20000, len(allD)))].mean(1); lo, hi = np.percentile(bs, [2.5, 97.5])
    ps = (sum(abs(np.mean([(d[t] * rng.choice([-1, 1], len(d[t]))).mean() for t in tasks])) >= abs(delta) - 1e-12
              for _ in range(20000)) + 1) / 20001
    pt = sum(abs(np.mean(tm * np.array(s))) >= abs(delta) - 1e-12 for s in itertools.product([-1, 1], repeat=len(tasks))) / 2 ** len(tasks)
    w = int((allD > 0).sum()); l = int((allD < 0).sum()); n = w + l; k = min(w, l)
    sp = min(1.0, 2 * sum(comb(n, i) for i in range(k + 1)) / 2 ** n) if n else 1.0
    res = (lo > 0 or hi < 0) and ps < 0.05 and pt < 0.05
    return dict(n=len(allD), delta=delta, lo=lo, hi=hi, w=w, l=l, sp=sp, ps=ps, pt=pt, tpos=int((tm > 0).sum()),
                changed=int((allD != 0).sum()), resolved=res, per_task={t: d[t].mean() for t in tasks},
                mean_m=np.mean([m[t].mean() for t in tasks]) * 100, mean_b=np.mean([b[t].mean() for t in tasks]) * 100)

out = ["# Second model: Qwen2.5-7B-Instruct (RTX PRO 6000 Blackwell 96 GB, bf16, eager attention)", "",
       "Generated by experiments/qwen_checks_report.py. LongBench dev split (samples 0-50 of the 8 English tasks, 400 paired), "
       "max_length 8000, 5 % budget, sink 4, recent 10 %, 64 new tokens. Every pair is method vs base on the same GPU. "
       "Delta = mean paired difference x100; CI = 20,000-resample bootstrap over the concatenated pairs; sign test two-sided; "
       "perm-s = 20,000 sign-flip permutations over samples; perm-t = exact sign flip over the 8 task means; "
       "resolved = CI excludes 0 and both permutation p < 0.05.", "",
       "| comparison | n | Delta x100 | 95 % CI | wins/losses (sign p) | perm-s | perm-t | tasks > 0 | changed | resolved | method mean | base mean |",
       "|---|---|---|---|---|---|---|---|---|---|---|---|"]
per_task_rows = []
for label, d, suf, bd, bsuf in ROWS:
    m, b = load(d, suf), load(bd, bsuf)
    if len(m) != 8 or len(b) != 8:
        out.append(f"| {label} | MISSING ({len(m)} method / {len(b)} base task files) |||||||||||"); continue
    r = paired(m, b)
    out.append(f"| {label} | {r['n']} | {r['delta']:+.2f} | [{r['lo']:+.2f}, {r['hi']:+.2f}] | {r['w']}/{r['l']} ({r['sp']:.3f}) | "
               f"{r['ps']:.3f} | {r['pt']:.3f} | {r['tpos']}/8 | {r['changed']} | {'yes' if r['resolved'] else 'no'} | {r['mean_m']:.2f} | {r['mean_b']:.2f} |")
    per_task_rows.append((label, r["per_task"]))
tasks = sorted(per_task_rows[0][1]) if per_task_rows else []
out += ["", "## Per-task Delta x100", "", "| comparison | " + " | ".join(tasks) + " |", "|---|" + "---|" * len(tasks)]
for label, pt in per_task_rows:
    out.append(f"| {label} | " + " | ".join(f"{pt[t]:+.2f}" for t in tasks) + " |")
# truncation and absolute means from the dense CSV
for f in glob.glob(os.path.join(D, "dense", "*.csv")):
    rows = list(csv.reader(open(f))); h = rows[1]; r = rows[2]
    out += ["", "## Middle-truncation at max_length 8000 (dense run, of 50 per task)", "",
            "| " + " | ".join(h[i].replace("_truncated_samples", "") for i in range(len(h)) if h[i].endswith("truncated_samples")) + " |",
            "|" + "---|" * sum(1 for x in h if x.endswith("truncated_samples")),
            "| " + " | ".join(r[i] for i in range(len(h)) if h[i].endswith("truncated_samples")) + " |"]
# merge counters
out += ["", "## Merge / routing counters (summed over the 400 samples' prefill records)", ""]
for d in ("otkv8", "keepkv", "keepkv_fixed", "selkv", "kvmerger"):
    p = os.path.join(D, d, "merge_stats.jsonl")
    if not os.path.exists(p):
        continue
    tot = {}
    for line in open(p):
        try:
            rec = json.loads(line)
        except Exception:
            continue
        if rec.get("stage", "prefill") != "prefill":
            continue
        for k, v in rec.get("stats", {}).items():
            if isinstance(v, (int, float)):
                tot[k] = tot.get(k, 0) + v
    keys = [k for k in ("evicted", "evicted_tokens", "merged", "merged_tokens", "routed", "dropped_empty_bucket", "sets", "candidates") if k in tot]
    out.append(f"- `{d}`: " + ", ".join(f"{k} {tot[k]:.4g}" for k in keys))
# NIAH
out += ["", "## Needle retrieval, 100 positions (10 context lengths 1k-8k x 10 depths)", "", "| run | method | accuracy |", "|---|---|---|"]
for d in ("niah100_c05", "niah100_c05_dense", "niah100_c02"):
    for f in glob.glob(os.path.join(D, d, "*.csv")):
        rows = list(csv.reader(open(f)))
        for r in rows[2:]:
            out.append(f"| {d} | {r[0]} | {r[1]} |")
open(os.path.join(D, "REPORT.md"), "w").write("\n".join(out) + "\n")
print("\n".join(out))
